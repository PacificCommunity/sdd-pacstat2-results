# convert a vector of mixed date types (see example below) to correct dates,
# going to the earliest month of the period and earliest day of the month. So
# 2026-Q2 gotes to 2026-04-01, and 2026-03 goes to 2026-03-01 and 2026 goes to
# 2026-01-01
#' @param x a vector of characters
flexi_date <- function(x) {
  out <- rep(as.Date(NA), length(x))

  year_idx <- stringr::str_detect(x, "^\\d{4}$")
  month_idx <- stringr::str_detect(x, "^\\d{4}-\\d{2}$")
  quarter_idx <- stringr::str_detect(x, "^\\d{4}-Q[1-4]$")

  out[year_idx] <- lubridate::ymd(paste0(x[year_idx], "-01-01"))
  out[month_idx] <- lubridate::ymd(paste0(x[month_idx], "-01"))

  q <- as.integer(str_sub(x[quarter_idx], 7, 7))
  month <- c("01", "04", "07", "10")[q]

  out[quarter_idx] <- lubridate::ymd(
    paste0(str_sub(x[quarter_idx], 1, 4), "-", month, "-01")
  )

  out
}

test_obs_time <- c(2019, "2025-Q2", "2026-03")
stopifnot(all(
  flexi_date(test_obs_time) ==
    as.Date(c("2019-01-01", "2025-04-01", "2026-03-01"))
))

